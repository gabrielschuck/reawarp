"""Builds the ReaPack index (index.xml), the action files (actions/) and the
release ZIP (dist/) for the version in the header of reawarp.lua.

Usage: python tools/make_index.py

Each release: raise "@version" (and "@changelog") in reawarp.lua, run this,
commit, tag "v<version>", push the tag and attach dist/reawarp-<version>.zip to
the GitHub release. The index links the files of that tag, and keeps the
earlier versions.

Copyright (C) 2026 Gabriel Schuck. GPL-3.0-or-later (see LICENSE).
"""
import datetime
import os
import re
import urllib.parse
import xml.etree.ElementTree as ET
import zipfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
REPO = 'https://github.com/gabrielschuck/reawarp'
CATEGORY = 'Tempo'
MAIN = 'reawarp.lua'
BACKEND = [('backend/reawarp_beat_this.py', None),
           ('backend/install_beat_this.bat', 'windows'),
           ('backend/install_beat_this.sh', 'darwin'),
           ('backend/install_beat_this.sh', 'linux')]


def header():
    src = open(os.path.join(ROOT, MAIN), encoding='utf-8').read()
    version = re.search(r'^-- @version (\S+)', src, re.M).group(1)
    author = re.search(r'^-- @author (.+)$', src, re.M).group(1).strip()
    desc = re.search(r'^-- @description (.+)$', src, re.M).group(1).strip()
    m = re.search(r'^-- @changelog\n((?:--   .*\n)+)', src, re.M)
    changelog = '\n'.join(l[5:] for l in m.group(1).splitlines()) if m else ''
    actions = re.findall(r'\{ "(\w+)", "(reawarp - [^"]+\.lua)" \}', src)
    return src, version, author, desc, changelog, actions


def stub(action, main=MAIN, up='../', noindex=False):
    # the same text core.install_actions writes (action_body in reawarp.lua)
    return (('-- @noindex\n' if noindex else '')
            + '-- Generated by reawarp.lua. Do not edit: all the code is in reawarp.lua.\n'
            f'REAWARP_ACTION = "{action}"\n'
            'dofile(debug.getinfo(1, "S").source:match("^@?(.*[\\\\/])") .. "' + up + main + '")\n')


# ReaTeam/ReaScripts layout: the main file in a category folder with the
# author's prefix, the other files in a folder of the same name
RT_CATEGORY = 'Stretch Markers'
RT_NAME = 'GabrielSchuck_reawarp'
RT_ABOUT = """# reawarp

Audio warping for REAPER, in the spirit of Ableton Live's Warp. reawarp detects the beats
of a song, including songs whose tempo drifts or changes, with the neural detector
Beat This!, and then:

- **Warp**: fits the item to the project tempo (stretch markers on the beats);
- **Tempo map**: makes the project follow the song (tempo markers on the beats);
- **Groove Match**: makes other items (a loop, another recording) follow the beats of a
  reference item;
- **Multitrack follower sync**: the items grouped with the one you warp follow it;
- **Audio quantize via MIDI**: moves the attacks of the audio onto the notes of a MIDI
  item (straight, swing, a shuffle...).

Wrong beats can be fixed from the keyboard (next/previous beat marker, move, add, delete,
shift half a beat). Everything uses REAPER's native menus and dialogs and works with
screen readers (OSARA). Messages in English, Portuguese and Spanish.

**Requirement**: the Beat This! detector, installed with one click from the reawarp menu
(about 350 MB downloaded, 800 MB on disk, its own Python, no system Python needed;
Windows, macOS and Linux). It can be uninstalled from the same menu.

Run the main script for the menu; every action is also in the Action List as
"reawarp - ...". Full documentation (English, Portuguese, Spanish):
https://github.com/gabrielschuck/reawarp"""


def reateam(src, version, author, desc, changelog, actions):
    """dist/reateam/: the files of a pull request to ReaTeam/ReaScripts."""
    out = os.path.join(ROOT, 'dist', 'reateam', RT_CATEGORY)
    sub = os.path.join(out, RT_NAME)
    os.makedirs(os.path.join(sub, 'actions'), exist_ok=True)
    os.makedirs(os.path.join(sub, 'backend'), exist_ok=True)
    main = RT_NAME + '.lua'
    prefix = RT_NAME.split('_')[0] + '_'
    for old in os.listdir(os.path.join(sub, 'actions')):
        os.remove(os.path.join(sub, 'actions', old))
    for action, name in actions:
        with open(os.path.join(sub, 'actions', prefix + name), 'w', encoding='utf-8', newline='\n') as f:
            f.write(stub(action, main, '../../', noindex=True))
    for rel in sorted({rel for rel, _ in BACKEND}):
        data = open(os.path.join(ROOT, rel), 'rb').read()
        if rel.endswith('.py'):
            data = b'# @noindex\n' + data   # part of the package, not a package
        open(os.path.join(sub, rel), 'wb').write(data)
    lines = [f'-- @description {desc}', f'-- @author {author}', f'-- @version {version}',
             '-- @license GPL-3.0-or-later', '-- @changelog']
    lines += ['--   ' + l for l in changelog.splitlines()]
    lines += ['-- @links', '--   GitHub https://github.com/gabrielschuck/reawarp', '-- @about']
    lines += [('--   ' + l).rstrip() for l in RT_ABOUT.splitlines()]
    lines += ['-- @provides']
    lines += [f'--   [main] {RT_NAME}/actions/{prefix}{name}' for _, name in actions]
    for rel, platform in BACKEND:
        lines.append(f'--   {"[" + platform + "] " if platform else ""}{RT_NAME}/{rel}')
    body = src[src.index('\n\n') + 1:]   # the file without its own header
    with open(os.path.join(out, main), 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(lines) + '\n' + body)
    return out


def main():
    src, version, author, desc, changelog, actions = header()
    os.makedirs(os.path.join(ROOT, 'actions'), exist_ok=True)
    for action, name in actions:
        with open(os.path.join(ROOT, 'actions', name), 'w', encoding='utf-8', newline='\n') as f:
            f.write(stub(action))

    path = os.path.join(ROOT, 'index.xml')
    if os.path.exists(path):
        index = ET.parse(path).getroot()
    else:
        index = ET.Element('index', version='1', name='reawarp')
        ET.SubElement(index, 'metadata')
        ET.SubElement(index.find('metadata'), 'link', rel='website').text = REPO
    cat = index.find(f"category[@name='{CATEGORY}']")
    if cat is None:
        cat = ET.SubElement(index, 'category', name=CATEGORY)
    pkg = cat.find(f"reapack[@name='{MAIN}']")
    if pkg is None:
        pkg = ET.SubElement(cat, 'reapack', name=MAIN, type='script', desc=desc)
        meta = ET.SubElement(pkg, 'metadata')
        ET.SubElement(meta, 'link', rel='website').text = REPO
    pkg.set('desc', desc)
    old = pkg.find(f"version[@name='{version}']")
    if old is not None:
        pkg.remove(old)
    ver = ET.SubElement(pkg, 'version', name=version, author=author,
                        time=datetime.datetime.now(datetime.timezone.utc).strftime('%Y-%m-%dT%H:%M:%SZ'))
    ET.SubElement(ver, 'changelog').text = changelog
    base = f'{REPO}/raw/v{version}/'

    def source(rel, **attrs):
        e = ET.SubElement(ver, 'source', **attrs)
        e.text = base + urllib.parse.quote(rel)
    source(MAIN, main='main')
    for _, name in actions:
        source('actions/' + name, file='actions/' + name, main='main')
    for rel, platform in BACKEND:
        source(rel, file=rel, **({'platform': platform} if platform else {}))
    ET.indent(index)
    ET.ElementTree(index).write(path, encoding='utf-8', xml_declaration=True)

    os.makedirs(os.path.join(ROOT, 'dist'), exist_ok=True)
    zpath = os.path.join(ROOT, 'dist', f'reawarp-{version}.zip')
    files = [MAIN, 'README.md', 'README.pt-BR.md', 'README.es.md', 'LICENSE'] + ['actions/' + n for _, n in actions] \
        + sorted({rel for rel, _ in BACKEND})
    with zipfile.ZipFile(zpath, 'w', zipfile.ZIP_DEFLATED) as z:
        for rel in files:
            z.write(os.path.join(ROOT, rel), 'reawarp/' + rel)
    rt = reateam(src, version, author, desc, changelog, actions)
    print(f'version {version}: index.xml, {len(actions)} actions, {zpath}, ReaTeam files in {rt}')


if __name__ == '__main__':
    main()
